const PORNOMBRE = new Map(ICONOS.map(([n, C]) => [n, C]));

/** Los colores de Notion para iconos (sus tonos de texto); se adaptan al tema por variable. */
export const COLORES_ICONO: [string, string][] = [
  ["gray", "Gris"],
  ["brown", "Marrón"],
  ["orange", "Naranja"],
  ["yellow", "Amarillo"],
  ["green", "Verde"],
  ["blue", "Azul"],
  ["purple", "Morado"],
  ["pink", "Rosa"],
  ["red", "Rojo"],
];

export const colorIcono = (color: string) => `var(--ico-${COLORES_ICONO.some(([c]) => c === color) ? color : "gray"})`;

export const esIconoLucide = (icon?: string | null): boolean => !!icon && icon.startsWith("icono:");

export const iconoLucide = (nombre: string, color: string) => `icono:${nombre}:${color}`;

/** «icono:rocket:orange» → su componente y color; null si no es de estos (o ya no existe). */
export function leeIcono(icon: string): { C: LucideIcon; nombre: string; color: string } | null {
  const [, nombre = "", color = "gray"] = icon.split(":");
  const C = PORNOMBRE.get(nombre);
  return C ? { C, nombre, color } : null;
}
